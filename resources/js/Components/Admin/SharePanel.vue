<script setup>
import { onBeforeUnmount, ref, watch } from 'vue';
import QRCode from 'qrcode';
import Button from '@/Components/UI/Button.vue';

const props = defineProps({
    playUrl: { type: String, required: true },
    slug: { type: String, required: true },
    published: { type: Boolean, required: true },
});

const qrSvg = ref('');
const qrPng = ref('');
const copied = ref(false);
const copyFailed = ref(false);
let copiedTimer = null;

// Regenerate whenever the URL changes (slug edited in the settings).
let generation = 0;
watch(
    () => [props.published, props.playUrl],
    async ([published, url]) => {
        const current = ++generation;
        if (!published) return;

        try {
            const [svg, png] = await Promise.all([
                QRCode.toString(url, { type: 'svg', margin: 1, color: { dark: '#134e4a' } }),
                QRCode.toDataURL(url, { width: 1024, margin: 2 }),
            ]);
            if (current !== generation) return;
            qrSvg.value = svg;
            qrPng.value = png;
        } catch (error) {
            console.error('Failed to generate QR code', error);
        }
    },
    { immediate: true },
);

const copy = async () => {
    try {
        await navigator.clipboard.writeText(props.playUrl);
        copyFailed.value = false;
        copied.value = true;
        clearTimeout(copiedTimer);
        copiedTimer = setTimeout(() => {
            copied.value = false;
        }, 2000);
    } catch {
        // Clipboard API is unavailable (e.g. plain http) — let the dozor copy by hand.
        copyFailed.value = true;
    }
};

const selectAll = (event) => event.target.select();

onBeforeUnmount(() => clearTimeout(copiedTimer));
</script>

<template>
    <section
        v-if="published"
        class="rounded-2xl bg-gradient-to-br from-teal-50 to-white p-4 ring-1 ring-teal-900/10"
        aria-labelledby="share-heading"
    >
        <h2 id="share-heading" class="text-sm font-semibold text-teal-900">Pro hráče</h2>
        <p class="mt-0.5 text-xs text-slate-600">Pošli odkaz nebo nech hráče načíst QR kód.</p>

        <div class="mt-3 flex gap-2">
            <input
                :value="playUrl"
                type="text"
                readonly
                aria-label="Odkaz na hru"
                class="min-w-0 flex-1 rounded-xl border-slate-300 bg-white px-3 py-1.5 text-sm text-slate-700 focus:border-teal-500 focus:ring-teal-500"
                @focus="selectAll"
            />
            <Button size="sm" :variant="copied ? 'secondary' : 'primary'" class="shrink-0" @click="copy">
                {{ copied ? 'Zkopírováno ✓' : 'Kopírovat' }}
            </Button>
        </div>
        <p v-if="copyFailed" class="mt-1 text-xs text-amber-700">Kopírování se nepovedlo — označ odkaz a zkopíruj ho ručně.</p>

        <div class="mt-4 flex items-center gap-4">
            <!-- v-html is safe here: the SVG is generated by the qrcode library from our own play URL, not from user text. -->
            <div
                class="h-40 w-40 shrink-0 rounded-xl bg-white p-2 shadow-sm ring-1 ring-slate-900/5 [&>svg]:h-full [&>svg]:w-full"
                role="img"
                aria-label="QR kód s odkazem na hru"
                v-html="qrSvg"
            />
            <div class="space-y-2">
                <p class="text-xs text-slate-600">Vytiskni QR kód a dej ho hráčům na start.</p>
                <a
                    v-if="qrPng"
                    :href="qrPng"
                    :download="`kompas-${slug}.png`"
                    class="inline-flex items-center justify-center gap-2 rounded-xl bg-white px-3 py-1.5 text-sm font-semibold text-slate-700 ring-1 ring-slate-300 transition hover:bg-slate-50 focus:outline-none focus-visible:ring-2 focus-visible:ring-teal-500 focus-visible:ring-offset-2"
                >
                    <svg class="h-4 w-4" viewBox="0 0 20 20" fill="currentColor" aria-hidden="true">
                        <path d="M10.75 2.75a.75.75 0 0 0-1.5 0v8.614L6.295 8.235a.75.75 0 1 0-1.09 1.03l4.25 4.5a.75.75 0 0 0 1.09 0l4.25-4.5a.75.75 0 0 0-1.09-1.03l-2.955 3.129V2.75Z" />
                        <path d="M3.5 12.75a.75.75 0 0 0-1.5 0v2.5A2.75 2.75 0 0 0 4.75 18h10.5A2.75 2.75 0 0 0 18 15.25v-2.5a.75.75 0 0 0-1.5 0v2.5c0 .69-.56 1.25-1.25 1.25H4.75c-.69 0-1.25-.56-1.25-1.25v-2.5Z" />
                    </svg>
                    Stáhnout QR
                </a>
            </div>
        </div>
    </section>

    <p v-else class="rounded-2xl border border-dashed border-slate-300 px-4 py-3 text-sm text-slate-500">
        Po publikování tu bude odkaz a QR kód pro hráče.
    </p>
</template>
